def global_themes():
    """Two look-and-feel packages without a layout script, so applying one never touches the panels.
    install.sh drops the widgetStyle line when it runs with --no-kvantum."""
    from PIL import Image
    root = os.path.join(ROOT, "global-themes")
    for v, g in GLOBAL.items():
        d = fresh(os.path.join(root, g["id"]))
        meta = {
            "KPackageStructure": "Plasma/LookAndFeel",
            "KPlugin": {
                "Authors": [{"Name": "Mathis Paquet (Daemon 2.0)"}, {"Name": "DaemonKDE (light variant, packaging)"}],
                "Category": "", "Description": g["desc"], "Id": g["id"], "License": "GPL-3.0",
                "Name": g["name"], "Website": "https://github.com/MathisP75/daemon-kde-mk2",
            },
            "Keywords": "Desktop;Workspace;Appearance;Look and Feel;Daemon;Cyberpunk;" + ("Light;" if v == "light" else "Dark;"),
            "X-Plasma-APIVersion": "2",
        }
        write(os.path.join(d, "metadata.json"), json.dumps(meta, indent=4) + "\n")
        write(os.path.join(d, "contents", "defaults"), "\n".join([
            "[kdeglobals][General]", f"ColorScheme={g['colors']}", "",
            "[kdeglobals][Icons]", f"Theme={g['icons']}", "",
            "[kdeglobals][KDE]", f"widgetStyle={g['style']}", "",
            "[plasmarc][Theme]", f"name={g['pstyle']}", "",
            "[kwinrc][org.kde.kdecoration2]", "library=org.kde.kwin.aurorae", f"theme={g['aurorae']}", "",
        ]))
        shot = Image.open(os.path.join(ROOT, "preview", "gallery", g["shot"])).convert("RGB")
        os.makedirs(os.path.join(d, "contents", "previews"))
        shot.resize((1920, 1080), Image.LANCZOS).save(os.path.join(d, "contents", "previews", "fullscreenpreview.jpg"), quality=88)
        shot.resize((600, 338), Image.LANCZOS).save(os.path.join(d, "contents", "previews", "preview.png"), optimize=True)


def main():
    color_scheme()
    kvantum()
    n_plasma = plasma_style()
    aurorae()
    n_icons = icons()
    konsole()
    global_themes()
    svg = wallpaper_svg()
    print(f"light/: color scheme, Kvantum, Plasma style ({n_plasma} SVGs), Aurorae, icons ({n_icons} SVGs), "
          f"Konsole, wallpaper SVG; global themes")
    if "--wallpaper" in sys.argv[1:]:
        render_wallpaper(svg)


if __name__ == "__main__":
    main()
